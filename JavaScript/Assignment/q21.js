let num = 3;

switch (num) {
    case 1:
        console.log("January");
        break;
    case 2:
        console.log("February ");
        break;
    case 3:
        console.log("March");
        break;

    case 12:
        console.log("December");
        break;
    default:
        console.log("Invalid month");
}